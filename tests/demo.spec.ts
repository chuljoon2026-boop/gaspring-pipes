test('전체/평면/도로 단면/교차부가 다르게 렌더링되고 회전과 로그아웃이 동작한다', async ({ page }, testInfo) => {
  test.setTimeout(120_000)
  const errors = collectErrors(page)
  await authenticate(page)
  const canvas = page.locator('canvas')
  const rendered: Buffer[] = []
  for (const [label, filename] of [['전체 3D', 'viewer-3d'], ['평면', 'viewer-plan'], ['도로 단면', 'viewer-section'], ['교차부', 'viewer-crossing']]) {
    const button = page.getByRole('button', { name: label, exact: true })
    await button.click()
    await expect(button).toHaveAttribute('aria-pressed', 'true')
    await frame(page)
    if (rendered.length) await expect.poll(async () => (await canvas.screenshot()).equals(rendered[rendered.length - 1])).toBe(false)
    const image = await canvas.screenshot()
    const stats = await sharp(image).stats()
    expect(Math.max(...stats.channels.slice(0, 3).map(channel => channel.stdev))).toBeGreaterThan(5)
    for (const previous of rendered) expect(image.equals(previous)).toBe(false)
    rendered.push(image)
    if (label === '도로 단면') await expect(page.getByText('지표 0 m', { exact: true })).toBeVisible()
    if (label === '교차부') await expect(page.locator('.crossing-clearance')).toContainText('0.75 m')
    await checkLayout(page)
    await capture(page, testInfo, filename)
  }
  await page.getByRole('button', { name: '전체 3D', exact: true }).click()
  await canvas.scrollIntoViewIfNeeded()
  await frame(page)
  const bounds = await canvas.boundingBox()
  expect(bounds).not.toBeNull()
  if (bounds) {
    // Prove the drag moved the camera from the renderer state, then confirm the canvas repainted.
    // Under heavy load, page-level screenshots can return a stale compositor frame even though the
    // scene rotated, so the pixel check uses the canvas element with a generous timeout.
    const readCamera = () => page.evaluate(async () => {
      const url = performance.getEntriesByType('resource').map(entry => entry.name).find(name => name.includes('react-three_fiber'))!
      const fiber = await import(/* @vite-ignore */ url)
      const state = fiber._roots.get(document.querySelector('canvas')).store.getState()
      return state.camera.position.toArray().map((value: number) => Number(value.toFixed(2))) as number[]
    })
    const cameraBefore = await readCamera()
    const before = await canvas.screenshot()
    const start = { x: bounds.x + bounds.width * 0.75, y: bounds.y + bounds.height * 0.3 }
    await page.mouse.move(start.x, start.y)
    await expect.poll(() => page.evaluate(({ x, y }) => document.elementFromPoint(x, y)?.tagName, start)).toBe('CANVAS')
    await frame(page)
    await page.mouse.down()
    await page.mouse.move(bounds.x + bounds.width * 0.45, bounds.y + bounds.height * 0.55, { steps: 12 })
    await page.mouse.up()
    await frame(page)
    await expect.poll(readCamera, { timeout: 15_000 }).not.toEqual(cameraBefore)
    await expect.poll(async () => (await canvas.screenshot()).equals(before), { timeout: 30_000 }).toBe(false)
  }
  await page.getByRole('button', { name: '시점 초기화', exact: true }).click()
  await page.getByRole('button', { name: '로그아웃', exact: true }).click()
  await page.goto(`${markerUrl}#worker`)
  await expect(page.getByRole('heading', { name: '작업 현장 확인', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

