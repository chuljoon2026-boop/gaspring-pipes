import { expect, test, type Page, type TestInfo } from '@playwright/test'
import sharp from 'sharp'

const markerUrl = '/?location=YS-001'
const unwantedCopy = /가스온|가상\s*현장|시[연현]용|굴착\s*주의\s*영역|신고\s*내역|홈\s*화면에\s*추가|시민의식|샘플|sample|워터마크|watermark/i

async function frame(page: Page) {
  await page.evaluate(async () => {
    await document.fonts.ready
    await new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve())))
  })
}
async function capture(page: Page, info: TestInfo, screen: string) {
  await frame(page)
  await page.screenshot({ path: `artifacts/screenshots/${info.project.name}-${screen}.png`, fullPage: true, animations: 'disabled' })
}
async function checkLayout(page: Page) {
  const size = await page.evaluate(() => ({ content: document.documentElement.scrollWidth, viewport: window.innerWidth }))
  expect(size.content).toBeLessThanOrEqual(size.viewport + 1)
  expect(await page.locator('body').innerText()).not.toMatch(unwantedCopy)
}
async function authenticate(page: Page) {
  await page.goto(`${markerUrl}#login`)
  await page.getByRole('button', { name: '시험용 정보 자동입력', exact: true }).click()
  await page.getByRole('button', { name: '현장 확인', exact: true }).click()
  await expect(page).toHaveURL(/location=YS-001#worker$/)
  await page.getByRole('button', { name: /3D 배관 보기/ }).click()
  await expect(page.locator('canvas')).toBeVisible()
  await expect(page.getByRole('button', { name: '수소 GP-001 상세 정보', exact: true })).toBeVisible()
}
function collectErrors(page: Page) {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  return errors
}

async function fitsScreen(page: Page) {
  const size = await page.evaluate(() => ({ width: document.documentElement.scrollWidth, height: document.documentElement.scrollHeight, viewportWidth: innerWidth, viewportHeight: innerHeight }))
  expect(size.width).toBeLessThanOrEqual(size.viewportWidth + 1)
  expect(size.height).toBeLessThanOrEqual(size.viewportHeight + 1)
}

